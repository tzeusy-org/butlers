#!/usr/bin/env python3
"""Render the small public recovery projection; --check refuses stale output."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from butlers.connectors.catalog import public_recovery_capabilities  # noqa: E402

OUTPUT = ROOT / "frontend/src/components/ingestion/connectors/connector-catalog.gen.ts"


def render() -> str:
    rows = {
        selector: {"kind": kind, "healthScopeOptIn": health}
        for selector, (kind, health) in sorted(public_recovery_capabilities().items())
    }
    return (
        "// Generated by scripts/render_connector_catalog.py; do not edit.\n"
        "// Routing capabilities only; no credential or observed grant state.\n"
        "export const CONNECTOR_RECOVERY_CAPABILITIES = "
        + json.dumps(rows, indent=2, ensure_ascii=True)
        + " as const\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print("Connector recovery projection is stale; run scripts/render_connector_catalog.py")
            return 1
        return 0
    OUTPUT.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
