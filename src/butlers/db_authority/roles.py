"""Strict server-owned roster projection, independent of runtime config discovery."""

from __future__ import annotations

import re
import tomllib
from dataclasses import dataclass, replace
from pathlib import Path

_ROSTER_ROOT = Path(__file__).resolve().parents[3] / "roster"
_IDENTIFIER = re.compile(r"[a-z_][a-z0-9_]{0,62}\Z")


class AuthorityError(RuntimeError):
    """Closed diagnostic; the original failure remains available through its cause."""


def _identifier(value: object) -> str:
    if not isinstance(value, str) or _IDENTIFIER.fullmatch(value) is None:
        raise AuthorityError("Runtime roster identity is invalid")
    return value


@dataclass(frozen=True)
class RuntimeProfile:
    """Held primary identity, not authority inferred from a private search path."""

    database: str
    primary_schema: str
    role: str
    runtime_roles: tuple[str, ...]
    private_schemas: tuple[str, ...] = ()
    modules: tuple[str, ...] = ()


def _roster_identities() -> tuple[tuple[str, str, str, tuple[str, ...], tuple[str, ...]], ...]:
    """One complete validated source census; never discovery-derived privileges."""
    try:
        if not _ROSTER_ROOT.is_dir():
            raise AuthorityError("Runtime roster authority is unavailable")
        identities = []
        names: set[str] = set()
        schemas: set[tuple[str, str]] = set()
        for entry in sorted(_ROSTER_ROOT.iterdir()):
            source = entry / "butler.toml"
            if not entry.is_dir():
                continue
            if not source.exists():
                if entry.name in {"shared", "__pycache__"}:
                    # Shared instructions and Python's generated bytecode are
                    # fixed non-roster directories, never identity evidence.
                    continue
                raise AuthorityError("Runtime roster identity is missing")
            if entry.is_symlink() or source.is_symlink() or not source.is_file():
                raise AuthorityError("Runtime roster authority is ambiguous")
            with source.open("rb") as stream:
                document = tomllib.load(stream)
            butler = document["butler"]
            name = _identifier(butler["name"])
            db = butler["db"]
            target = _identifier(db["name"])
            primary = db.get("schema", name if target == "butlers" else None)
            primary = _identifier(primary)
            derived = _identifier(f"butler_{name}_rw")
            if name != entry.name or name in names or (target, primary) in schemas:
                raise AuthorityError("Runtime roster authority is ambiguous")
            names.add(name)
            schemas.add((target, primary))
            memory = document.get("modules", {}).get("memory", {})
            private = memory.get("memory_schema")
            private_schemas = (
                () if private is None or private == primary else (_identifier(private),)
            )
            modules = document.get("modules", {})
            if not isinstance(modules, dict):
                raise AuthorityError("Runtime module authority is invalid")
            names_in_modules = tuple(sorted(_identifier(name) for name in modules))
            identities.append((target, primary, derived, private_schemas, names_in_modules))
        if not identities:
            raise AuthorityError("Runtime roster authority is empty")
        # A private schema cannot silently alias a different primary or private owner.
        owned = set(schemas)
        for target, _, _, private, _ in identities:
            for child in private:
                if (target, child) in owned:
                    raise AuthorityError("Runtime roster authority is ambiguous")
                owned.add((target, child))
        return tuple(identities)
    except AuthorityError:
        raise
    except (OSError, ValueError, KeyError, TypeError, AttributeError) as exc:
        raise AuthorityError("Runtime roster authority is unavailable") from exc


def runtime_profiles(database: str) -> tuple[RuntimeProfile, ...]:
    """All declared runtime/private profiles in one selected database."""
    identities = _roster_identities()
    selected = [row for row in identities if row[0] == database]
    if not selected:
        raise AuthorityError("Runtime database identity is not declared")
    roles = tuple(sorted(row[2] for row in selected))
    return tuple(
        RuntimeProfile(db, schema, role, roles, private, modules)
        for db, schema, role, private, modules in selected
    )


def compile_deployment_profiles(
    database: str, *, source_database: str
) -> tuple[RuntimeProfile, ...]:
    """Compile a selected migrator deployment from one existing source manifest.

    This is an administrative source compiler, not a serving admission fallback.
    It cannot accept a role/schema/module list. Disposable producers use the same
    compiler for their independently selected database; runtime callers continue
    to use strict runtime_profiles against their actual fixed source identity.
    """
    _identifier(database)
    return tuple(
        replace(profile, database=database) for profile in runtime_profiles(source_database)
    )


def load_runtime_profile(database: str, schema: str | None, role: str) -> RuntimeProfile:
    """Select immutable primary/private authority from the complete fixed roster."""
    selected = [profile for profile in runtime_profiles(database) if profile.role == role]
    if len(selected) != 1 or schema not in (None, selected[0].primary_schema):
        raise AuthorityError("Runtime database identity is not declared")
    return selected[0]


@dataclass(frozen=True)
class PurposeProfile:
    """Fixed service capability, distinct from a daemon/private-schema identity."""

    database: str
    purpose: str
    role: str
    runtime_roles: tuple[str, ...]
    direct_login: bool = False


def purpose_profile(database: str, purpose: str) -> PurposeProfile:
    """Project a source-owned purpose. Request data cannot add roles or privileges."""
    # Serving purposes bind the actual deployment database, just like daemons.
    # The administrative compiler has a distinct entry point for disposable DBs.
    runtime_profiles(database)
    fixed = {
        "dashboard": ("dashboard_api", False),
        "connector": ("connector_writer", False),
        "credential": ("credential_store_writer", False),
        "restore_executor": ("restore_drill_executor", True),
    }
    if purpose not in fixed:
        raise AuthorityError("Database purpose is not declared")
    role, direct = fixed[purpose]
    return PurposeProfile(database, purpose, role, (role,), direct)
