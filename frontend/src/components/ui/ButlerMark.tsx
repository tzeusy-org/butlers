// ---------------------------------------------------------------------------
// ButlerMark — canonical butler letter-mark primitive (bu-myje9)
//
// Renders a 16px square (4px radius) bearing the butler initial.
// Two tones:
//   "fill"    — solid category-hue background, white initial. Active state.
//   "neutral" — transparent background, category-hue initial, hairline border.
//
// This module is the single source of truth for the butler-name to identity
// hue mapping. The palette below is a module-private TypeScript map applied as
// an inline style, so no global CSS variable exists for another surface to
// reach for: identity colour is private by construction. Non-identity callers
// use typed helpers from `@/lib/visual-token-roles` instead.
//
// Doctrine: each butler's hue appears only on the butler letter-mark (colored
// squircle with initial). Never on backgrounds, borders, buttons, headers, or
// other chrome. Local categories use the separate --categorical-* ramp. They
// never share this identity pool.
// ---------------------------------------------------------------------------

// ---------------------------------------------------------------------------
// Hue mapping — single source of truth
// ---------------------------------------------------------------------------

/**
 * The twelve identity hues, in slot order, as [light, dark] oklch pairs.
 * `light-dark()` follows the `color-scheme` that index.css sets on `:root`
 * (light) and `.dark` (dark), so the mark tracks the theme without a variable.
 * Slot assignment is deterministic: known butlers use their roster index;
 * unknown names fall back to a multiplier-31 hash (mod 12) so distinct unknown
 * butlers still receive distinct colors.
 *
 * Slots 1-8 are the original ramp; 9-11 fill the largest hue-ring gaps so the
 * 11-butler roster has no collisions; 12 is spare headroom for the next butler
 * added to KNOWN_BUTLERS. openspec/specs/dashboard-design-language/spec.md
 * § Requirement: Butler Category Hues mirrors this table and MUST be
 * regenerated by hand whenever the table or KNOWN_BUTLERS changes.
 */
const BUTLER_HUES: readonly (readonly [light: string, dark: string])[] = [
  ["oklch(0.623 0.130 259.0)", "oklch(0.680 0.130 259.0)"], // 1 blue
  ["oklch(0.581 0.130 292.5)", "oklch(0.640 0.130 292.5)"], // 2 violet
  ["oklch(0.769 0.120 84.0)", "oklch(0.810 0.120 84.0)"], // 3 amber
  ["oklch(0.706 0.120 183.5)", "oklch(0.758 0.115 183.5)"], // 4 teal
  ["oklch(0.641 0.140 11.2)", "oklch(0.695 0.140 11.2)"], // 5 rose
  ["oklch(0.585 0.130 320.0)", "oklch(0.640 0.130 320.0)"], // 6 mauve
  ["oklch(0.717 0.120 208.5)", "oklch(0.770 0.115 208.5)"], // 7 cyan
  ["oklch(0.737 0.130 58.0)", "oklch(0.790 0.130 58.0)"], // 8 orange
  ["oklch(0.650 0.130 128.0)", "oklch(0.710 0.125 128.0)"], // 9 green
  ["oklch(0.620 0.150 346.0)", "oklch(0.680 0.145 346.0)"], // 10 raspberry
  ["oklch(0.580 0.140 234.0)", "oklch(0.640 0.135 234.0)"], // 11 indigo
  ["oklch(0.620 0.150 35.0)", "oklch(0.680 0.145 35.0)"], // 12 red-orange
]

/**
 * Canonical roster order. The slot a butler occupies in this list is its
 * permanent color slot. Add new butlers at the end; never reorder.
 *
 * Unknown names (not in this list) receive a hash-derived slot so they
 * remain visually distinct from each other and from known butlers. The
 * hash is deterministic across renders and sessions (multiplier-31 rolling hash).
 */
export const KNOWN_BUTLERS: readonly string[] = [
  "chronicler",
  "education",
  "finance",
  "general",
  "health",
  "home",
  "lifestyle",
  "messenger",
  "qa",
  "relationship",
  "travel",
]

/**
 * Multiplier-31 rolling hash (not djb2): maps any string to a non-negative integer.
 * Deterministic across renders and sessions.
 */
function hashName(name: string): number {
  let h = 0
  for (let i = 0; i < name.length; i++) {
    h = (h * 31 + name.charCodeAt(i)) | 0
  }
  return Math.abs(h)
}

/**
 * Resolve the CSS colour for the butler's identity hue.
 *
 * Known butlers use their roster-index slot (stable across all renders).
 * Unknown butlers use a hash-derived slot (stable for a given name, but not
 * guaranteed to be unique across all unknown names).
 */
function butlerHue(name: string): string {
  const idx = KNOWN_BUTLERS.indexOf(name)
  const [light, dark] = BUTLER_HUES[(idx !== -1 ? idx : hashName(name)) % BUTLER_HUES.length]
  return `light-dark(${light}, ${dark})`
}

// ---------------------------------------------------------------------------
// ButlerMark component
// ---------------------------------------------------------------------------

export interface ButlerMarkProps {
  /** Butler name. Drives both the initial glyph and the hue slot. */
  name: string
  /**
   * Visual tone:
   *   "fill"    — solid hue background, white initial. Use for active/selected state.
   *   "neutral" — transparent background, hue-colored initial, hairline border. Default.
   */
  tone?: "fill" | "neutral"
  /**
   * Size in pixels for the squircle. Defaults to 16.
   * Font size is scaled proportionally (60% of size).
   */
  size?: number
  /** Optional className forwarded to the root element. */
  className?: string
  /** Render the full butler name as a native hover label for initial-only callers. */
  showNameOnHover?: boolean
  /**
   * Agent type. "staffer" renders as a full circle (50% border-radius) to visually
   * distinguish infrastructure roles from user-facing butlers (squircle). Defaults to "butler".
   */
  type?: "butler" | "staffer"
}

/**
 * 16x16 px squircle bearing the butler initial, colored via the canonical
 * hue slot for this butler name.
 *
 * @example
 *   <ButlerMark name="health" tone="fill" />
 *   <ButlerMark name="qa" tone="neutral" />
 */
export function ButlerMark({
  name,
  tone = "neutral",
  size = 16,
  className,
  showNameOnHover = false,
  type = "butler",
}: ButlerMarkProps) {
  const hue = butlerHue(name)
  const initial = (name[0] ?? "?").toUpperCase()
  const fullName = type === "staffer" ? `${name} (staffer)` : name

  const baseStyle: React.CSSProperties = {
    width: size,
    height: size,
    borderRadius: type === "staffer" ? "50%" : Math.round(size * 0.25),
    display: "inline-flex",
    alignItems: "center",
    justifyContent: "center",
    fontFamily: "var(--font-sans)",
    fontWeight: 600,
    fontSize: `${(size * 0.6).toFixed(1)}px`, // 60% of size
    lineHeight: 1,
    flexShrink: 0,
  }

  const toneStyle: React.CSSProperties =
    tone === "fill"
      ? {
          backgroundColor: hue,
          color: "white",
          border: "none",
        }
      : {
          backgroundColor: "transparent",
          color: hue,
          border: `1px solid ${hue}`,
        }

  return (
    <span
      style={{ ...baseStyle, ...toneStyle }}
      className={className}
      title={showNameOnHover ? fullName : undefined}
      aria-label={fullName}
    >
      {initial}
    </span>
  )
}
